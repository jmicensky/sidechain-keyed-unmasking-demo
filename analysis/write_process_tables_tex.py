#!/usr/bin/env python3
"""LaTeX tables for the process comparison (group compression, Basic and
per-channel sidechain) on Construction and Public Transit.

Reads (all in analysis/):
  process_lhs_{comp,basic,perchannel}.csv      run_process_lhs.py
  process_matched.csv                          score_matched_processes.py
  sbr_matched_2scene_{comp,basic,perchannel}_best.tsv   sbr_matched_search

Writes (copied into the thesis repo by hand, like the other fragments):
  process_ranges_table.tex       (a) metric min/median/max per process and scene
  process_sensitivity_table.tex  (b) Spearman rho of each parameter with the
                                     SBR change and the Extended SII change
  process_matched_table.tex      (c) matched settings vs static gain at the same SBR
  process_settings_table.tex     (d) the matched settings themselves

    /usr/bin/python3 analysis/write_process_tables_tex.py
"""
import csv
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

HERE = Path(__file__).resolve().parent
PROCESSES = [("comp", "Group compression (single-band)"),
             ("basic", "Sidechain, Basic (summed bus)"),
             ("perchannel", "Sidechain, per-channel")]
SCENES = [("construction", "Construction"), ("publictransit", "Public Transit")]
TARGETS = [("HI", 5.1), ("NH", 12.2)]

# (column, label, decimals) for the metric tables.
METRICS = [("sbr_gain_db", r"SBR change (dB)", 1),
           ("bg_level_change_db", r"Background level change (dB)", 1),
           ("esii_gain", r"$\Delta$Extended SII", 3),
           ("static_sii_gain", r"$\Delta$Static SII", 3),
           ("estoi_gain", r"$\Delta$ESTOI", 3)]

PARAM_LABELS = {
    "threshold_db": "Threshold (dB)", "ratio": "Ratio", "knee_db": "Knee (dB)",
    "attack_ms": "Attack (ms)", "release_ms": "Release (ms)", "max_reduction_db": "Max reduction (dB)",
    "dialogue_threshold_db": "Dialogue threshold (dB)", "dialogue_ratio": "Dialogue ratio",
    "dialogue_attack_ms": "Dialogue attack (ms)", "dialogue_release_ms": "Dialogue release (ms)",
    "music_threshold_db": "Music threshold (dB)", "music_ratio": "Music ratio",
    "background_threshold_db": "Background threshold (dB)", "background_ratio": "Background ratio",
    "safety_threshold_db": "Safety threshold (dB)", "safety_ratio": "Safety ratio",
    "other_threshold_db": "Other threshold (dB)", "other_ratio": "Other ratio",
    "background_attack_ms": "Attack, non-Dialogue groups (ms)",
    "background_release_ms": "Release, non-Dialogue groups (ms)",
}

# Matched-setting parameter order per mode: sbr_matched_search.cpp dimsFor().
SETTING_DIMS = {
    "comp": ["dialogue_threshold_db", "dialogue_ratio", "dialogue_attack_ms", "dialogue_release_ms",
             "music_threshold_db", "music_ratio", "background_threshold_db", "background_ratio",
             "safety_threshold_db", "safety_ratio", "other_threshold_db", "other_ratio",
             "knee_db", "background_attack_ms", "background_release_ms"],
    "basic": ["threshold_db", "ratio", "knee_db", "attack_ms", "release_ms", "max_reduction_db"],
    "perchannel": ["music_threshold_db", "music_ratio", "background_threshold_db", "background_ratio",
                   "safety_threshold_db", "safety_ratio", "other_threshold_db", "other_ratio",
                   "knee_db", "attack_ms", "release_ms", "max_reduction_db"],
}

HEADER = "% Generated by analysis/write_process_tables_tex.py. Do not edit by hand.\n"


def signed(x, nd):
    s = f"{x:+.{nd}f}"
    if float(s) == 0:
        s = f"{0:.{nd}f}"
    return f"${s}$"


def lhs_rows(proc):
    with open(HERE / f"process_lhs_{proc}.csv") as f:
        return list(csv.DictReader(f))


def params_of(rows):
    cols = list(rows[0])
    return cols[cols.index("scene") + 1:cols.index("sbr_db")]


def ranges_table():
    lines, counts = [], []
    for proc, label in PROCESSES:
        rows = lhs_rows(proc)
        counts.append(f"{label}: {len(rows) // len(SCENES)}")
        for i, (col, mlabel, nd) in enumerate(METRICS):
            cells = []
            for s, _ in SCENES:
                a = np.array([float(r[col]) for r in rows if r["scene"] == s])
                cells += [signed(a.min(), nd), signed(np.median(a), nd), signed(a.max(), nd)]
            lines.append((label if i == 0 else "") + f" & {mlabel} & " + " & ".join(cells) + r" \\")
        lines.append(r"\addlinespace")
    lines.pop()
    return HEADER + r"""\begin{table}[H]
\centering
\footnotesize
\setstretch{1}  % single-spaced rows in the double-spaced thesis
\caption{\protect\todo{AI draft --- rewrite: Range of each metric over the Latin-hypercube parameter sweep of each process (points per scene: """ + "; ".join(counts) + r"""). Changes are relative to the unprocessed mix of the same scene, after loudness matching. The same parameter points were used in both scenes.}}
\label{tab:process-ranges}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}ll rrr rrr@{}}
\toprule
 & & \multicolumn{3}{c}{\textbf{Construction}} & \multicolumn{3}{c}{\textbf{Public Transit}} \\
\cmidrule(lr){3-5} \cmidrule(lr){6-8}
\textbf{Process} & \textbf{Metric} & \textbf{Min} & \textbf{Median} & \textbf{Max} & \textbf{Min} & \textbf{Median} & \textbf{Max} \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}%
}
\end{table}
"""


def sensitivity_table():
    lines = []
    for proc, label in PROCESSES:
        rows = lhs_rows(proc)
        for i, prm in enumerate(params_of(rows)):
            cells = []
            for s, _ in SCENES:
                r = [x for x in rows if x["scene"] == s]
                v = [float(x[prm]) for x in r]
                for target in ("sbr_gain_db", "esii_gain"):
                    rho = spearmanr(v, [float(x[target]) for x in r]).statistic
                    cells.append(signed(rho, 2))
            lines.append((label if i == 0 else "") + f" & {PARAM_LABELS[prm]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\addlinespace")
    lines.pop()
    return HEADER + r"""\begin{table}[H]
\centering
\footnotesize
\setstretch{1}  % single-spaced rows in the double-spaced thesis
\caption{\protect\todo{AI draft --- rewrite: Spearman rank correlation $\rho$ of each swept parameter with the SBR change and with the Extended SII change, per process and scene, over the parameter sweeps of Table~\ref{tab:process-ranges}.}}
\label{tab:process-sensitivity}
\begin{tabular}{@{}ll rr rr@{}}
\toprule
 & & \multicolumn{2}{c}{\textbf{Construction}} & \multicolumn{2}{c}{\textbf{Public Transit}} \\
\cmidrule(lr){3-4} \cmidrule(lr){5-6}
\textbf{Process} & \textbf{Parameter} & \textbf{$\rho$ SBR} & \textbf{$\rho$ ESII} & \textbf{$\rho$ SBR} & \textbf{$\rho$ ESII} \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""


def matched_table():
    with open(HERE / "process_matched.csv") as f:
        rows = list(csv.DictReader(f))
    get = lambda s, c, t: next(r for r in rows if r["scene"] == s and r["condition"] == c and r["target"] == t)
    cols = [("sbr_db", 2), ("bg_level_change_db", 2), ("dialogue_level_change_db", 2),
            ("esii_gain", 3), ("static_sii_gain", 3), ("estoi_gain", 3)]
    lines = []
    for s, sname in SCENES:
        u = get(s, "unprocessed", "")
        lines.append(r"\multicolumn{8}{@{}l}{\textbf{" + sname + r"} (unprocessed: SBR " + signed(float(u["sbr_db"]), 2)
                     + f"~dB, Extended SII {float(u['esii']):.3f}, static SII {float(u['static_sii']):.3f}, "
                     + f"ESTOI {float(u['estoi']):.3f})" + r"} \\")
        for t, tval in TARGETS:
            for j, (proc, label) in enumerate(PROCESSES):
                for cond, clabel in ((proc, label),
                                     (f"static_match_{proc}", None)):
                    r = get(s, cond, t)
                    if clabel is None:
                        clabel = r"\quad Static gain (" + signed(float(r["static_gain_db"]), 2) + r"~dB)"
                    tcell = f"{t} ${tval:+.1f}$" if (j == 0 and cond == proc) else ""
                    lines.append(f"{tcell} & {clabel} & "
                                 + " & ".join(signed(float(r[c]), nd) for c, nd in cols) + r" \\")
            lines.append(r"\addlinespace")
        lines.append(r"\midrule")
    lines.pop()
    return HEADER + r"""\begin{table}[H]
\centering
\footnotesize
\setstretch{1}  % single-spaced rows in the double-spaced thesis
\caption{\protect\todo{AI draft --- rewrite: Each process at its SBR-matched setting (Table~\ref{tab:process-settings}) next to a static background gain that reaches the same gated SBR. Targets are the hearing-impaired (HI, $+5.1$~dB) and normal-hearing (NH, $+12.2$~dB) optima of Johnson and Healy~\cite{johnsonhealy2024}; one setting per process and target serves both scenes. Every condition is loudness-matched to the unprocessed mix before scoring; level changes and metric changes are relative to the unprocessed mix. The static gain is the gain applied to the unprocessed background sum before loudness matching.}}
\label{tab:process-matched}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}ll rrr rrr@{}}
\toprule
\textbf{Target (dB)} & \textbf{Condition} & \textbf{SBR (dB)} & \textbf{Background (dB)} & \textbf{Dialogue (dB)} & \textbf{$\Delta$Ext.\ SII} & \textbf{$\Delta$Static SII} & \textbf{$\Delta$ESTOI} \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}%
}
\end{table}
"""


def settings_table():
    lines = []
    for proc, label in PROCESSES:
        vals = {}
        with open(HERE / f"sbr_matched_2scene_{proc}_best.tsv") as f:
            for line in f:
                name, mode, csv_vals = line.rstrip("\n").split("\t")
                vals[name.split("_")[-1]] = [float(x) for x in csv_vals.split(",")]
        dims = SETTING_DIMS[proc]
        assert all(len(v) == len(dims) for v in vals.values()), proc
        for i, prm in enumerate(dims):
            nd = 2 if "ratio" in prm else (0 if prm.endswith("_ms") and "release" in prm else 1)
            cells = [f"${vals[t][i]:.{nd}f}$" for t, _ in TARGETS]
            lines.append((label if i == 0 else "") + f" & {PARAM_LABELS[prm]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\addlinespace")
    lines.pop()
    return HEADER + r"""\begin{table}[H]
\centering
\footnotesize
\setstretch{1}  % single-spaced rows in the double-spaced thesis
\caption{\protect\todo{AI draft --- rewrite: SBR-matched settings: for each process and target, the single setting found by the two-scene search (Construction and Public Transit) whose gated SBR is closest to the target in both scenes, with the least processing. Group compression has no makeup gain; Dialogue is required to compress (mean gain reduction 1.5--6~dB in every scene). Sidechain settings share one detector keyed on raw Dialogue.}}
\label{tab:process-settings}
\begin{tabular}{@{}ll rr@{}}
\toprule
\textbf{Process} & \textbf{Parameter} & \textbf{HI ($+5.1$~dB)} & \textbf{NH ($+12.2$~dB)} \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""


def main():
    for name, fn in [("process_ranges_table.tex", ranges_table),
                     ("process_sensitivity_table.tex", sensitivity_table),
                     ("process_matched_table.tex", matched_table),
                     ("process_settings_table.tex", settings_table)]:
        (HERE / name).write_text(fn())
        print(f"wrote {HERE / name}")


if __name__ == "__main__":
    main()
