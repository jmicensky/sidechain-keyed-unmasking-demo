#!/usr/bin/env python3
"""LaTeX table: scene-to-scene SBR spread of ONE setting per mode and target.

Reads the "best" rows of the two-scene SBR-matched search
(analysis/sbr_matched_2scene_{comp,compmb,basic,perchannel,combined}.csv, from
`sbr_matched_search --scenes construction,publictransit --tag sbr_matched_2scene`)
and writes analysis/scene_spread_table.tex (also copied into the thesis
repo by hand, like the other *_table.tex fragments).

For each mode and target it shows the SBR the single best setting reaches in
each scene, the change from that scene's unprocessed SBR, and the spread
between scenes. SBR here is the search's gated metric (sbr_sweep.cpp: speech-
active samples, 20 ms frames within 40 dB of the Dialogue peak), not the J&H
per-utterance SBR of volume_only.cpp.
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCENES = [("construction", "Construction"), ("publictransit", "Public Transit")]
# Unprocessed gated SBR per scene (analysis/sbr_sweep_findings.txt, same gate).
UNPROCESSED = {"construction": 1.31, "publictransit": -4.50}
TARGETS = [("HI", 5.1), ("NH", 12.2)]
MODES = [("comp", "Group compression"), ("compmb", "Group compression (multiband)"),
         ("basic", "Sidechain (Basic)"),
         ("perchannel", "Sidechain (per-channel)"), ("combined", "Combined")]


def best_rows(mode):
    with open(HERE / f"sbr_matched_2scene_{mode}.csv") as f:
        return {r["target"]: r for r in csv.DictReader(f) if r["stage"] == "best"}


def signed(x):
    return f"${x:+.2f}$"


lines = []
for mode, label in MODES:
    rows = best_rows(mode)
    for tname, tval in TARGETS:
        r = rows[tname]
        sbr = {s: float(r[f"{s}_sbr_db"]) for s, _ in SCENES}
        cells = []
        for s, _ in SCENES:
            cells += [signed(sbr[s]), signed(sbr[s] - UNPROCESSED[s])]
        spread = sbr["construction"] - sbr["publictransit"]
        spread = 0.0 if abs(spread) < 0.005 else spread  # no "-0.00"
        worst = max(abs(sbr[s] - tval) for s, _ in SCENES)
        lines.append(f"{label} & {tname} ${tval:+.1f}$ & " + " & ".join(cells)
                     + f" & ${spread:.2f}$ & ${worst:.2f}$ \\\\")
    lines.append("\\addlinespace")
lines.pop()

u = UNPROCESSED
tex = r"""% Scene-to-scene SBR spread of one setting per mode and target.
% Generated by analysis/write_scene_spread_tex.py from the two-scene
% SBR-matched search (analysis/sbr_matched_2scene_*.csv). Do not edit by hand.
\begin{table}[H]
\centering
\footnotesize
\setstretch{1}  % single-spaced rows in the double-spaced thesis
\caption{\protect\todo{AI draft --- rewrite: SBR reached in each scene by the single best setting found for each processing mode and target (two-scene search, Construction and Public Transit). ``Change'' is the SBR change from each scene's unprocessed mix; ``Spread'' is the Construction SBR minus the Public Transit SBR; ``Worst miss'' is the larger distance from the target. SBR is the gated speech-active measure used by the search.}}
\label{tab:scene-spread}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}ll rr rr rr@{}}
\toprule
 & & \multicolumn{2}{c}{\textbf{Construction}} & \multicolumn{2}{c}{\textbf{Public Transit}} & & \\
\cmidrule(lr){3-4} \cmidrule(lr){5-6}
\textbf{Mode} & \textbf{Target (dB)} & \textbf{SBR (dB)} & \textbf{Change} & \textbf{SBR (dB)} & \textbf{Change} & \textbf{Spread (dB)} & \textbf{Worst miss (dB)} \\
\midrule
Unprocessed & -- & """ + f"{signed(u['construction'])} & -- & {signed(u['publictransit'])} & -- & ${u['construction'] - u['publictransit']:.2f}$ & -- \\\\" + r"""
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}%
}
\end{table}
"""
out = HERE / "scene_spread_table.tex"
out.write_text(tex)
print(f"wrote {out}")
