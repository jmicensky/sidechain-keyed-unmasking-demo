#!/usr/bin/env python3
"""Writes the Unity handoff for the SBR-matched settings, from the analysis TSVs.

Inputs (all produced by analysis/run_sbr_matched.sh):
  analysis/sbr_matched_settings.tsv        rounded web settings per mode x target
  analysis/sbr_matched_{mode}.csv          parameter names (header)
  analysis/sbr_matched_input_levels.tsv    per-channel input levels
  analysis/sbr_matched_gain_reduction.tsv  web GR + per-scene LL Dynamics GR-matched thresholds
  analysis/sbr_matched_lld_settings.tsv    final LL Dynamics settings + their GR per scene
  analysis/sbr_matched_lld_sbr.tsv         SBR: web vs LL Dynamics (before/after trim)
  exports/sbr_matched/render_stats.tsv     per-render SBR + Dialogue dynamic range

Output: unity/SBR_SETTINGS_HANDOFF.md, copied to the Unity project's Docs/ if it exists.
"""
import csv
import shutil
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
A = REPO / "analysis"
UNITY_DOCS = Path.home() / "Documents/UIC/THESIS RESEARCH/Modified_Johnson_Healy/Docs"
SCENES = ["construction", "publictransit", "restaurant"]
SCENE_LABEL = {"construction": "Construction", "publictransit": "Public Transit", "restaurant": "Restaurant"}
MODE_LABEL = {"basic": "Basic unmasking", "comp": "Group compression", "combined": "Combined (group compression then unmasking)"}
SNAPSHOT = {"basic": "Unmasked", "comp": "GroupCompress", "combined": "GroupCompressed>Unmasked"}
TARGET = {"HI": ("hearing-impaired optimum", 5.1, "4.7 to 5.8"), "NH": ("normal-hearing optimum", 12.2, "2.8 to 22.4")}
CHANNELS = ["Dialogue", "Music", "Background", "Safety", "Other"]


def tsv(path):
    with open(path) as f:
        return list(csv.DictReader(f, delimiter="\t"))


def f1(x):
    return f"{float(x):.1f}"


def signed(x):
    return f"{float(x):+.1f}"


def web_params(mode, values):
    with open(A / f"sbr_matched_{mode}.csv") as f:
        header = next(csv.reader(f))
    names = []
    for h in header[2:]:
        if h.startswith(tuple(s + "_" for s in SCENES)):
            break
        names.append(h)
    return dict(zip(names, (float(v) for v in values.split(","))))


def main():
    settings = [line.split("\t") for line in (A / "sbr_matched_settings.tsv").read_text().splitlines() if line]
    levels = tsv(A / "sbr_matched_input_levels.tsv")
    web_gr = tsv(A / "sbr_matched_gain_reduction.tsv")
    lld = tsv(A / "sbr_matched_lld_settings.tsv")
    lld_sbr = tsv(A / "sbr_matched_lld_sbr.tsv")
    stats_path = REPO / "exports/sbr_matched/render_stats.tsv"
    renders = tsv(stats_path) if stats_path.exists() else []
    raw_range = {r["scene"]: r["dialogue_range_db"] for r in renders if r["label"] == "S0_unprocessed"}
    lag = next(k for k in lld_sbr[0] if k.startswith("lld_trimmed_sbr_db_lag")).split("lag")[-1]

    o = []
    w = o.append
    w("# Handoff: SBR-matched dynamics settings for the Unity test sequence")
    w("")
    w("Generated by `demo_engine/analysis/write_unity_sbr_handoff.py` from the sweep data; do not edit numbers by hand,")
    w("re-run `demo_engine/analysis/run_sbr_matched.sh` instead. For the Unity session working in `Modified_Johnson_Healy`.")
    w("")
    w("## 1. What \"best\" means here")
    w("")
    w("- **Metric:** Johnson & Healy (2024) speech-to-background ratio. SBR = speech-active RMS of the processed Dialogue")
    w("  group / RMS of the processed sum of the other four groups (Music, Background, Safety, Other), broadband, unweighted,")
    w("  both channels. \"Speech-active\" = 20 ms frames where the raw Dialogue stem is within 40 dB of its peak.")
    w("- **Targets:** HI +5.1 dB (J&H 95 % window 4.7 to 5.8 dB) and NH +12.2 dB (window 2.8 to 22.4 dB). Participants are")
    w("  mostly normal-hearing, so **NH is the primary target**; HI is the secondary condition.")
    w("- **One setting per mode and target, shared by all three test scenes** (Construction, Public Transit, Restaurant):")
    w("  the search minimizes the worst-scene |SBR - target|, then prefers the setting with the least gain reduction.")
    w("- **The SBR change comes from the dynamics only:** every makeup gain and the key gain are fixed at 0 dB.")
    w("- **Dialogue is compressed on purpose** in Group compression and Combined (ratio 2-4:1, mean gain reduction")
    w("  1.5-6 dB in every scene), for intelligibility; the background groups have to supply the SBR. Its effect is")
    w("  reported as Dialogue dynamic range (J&H Fig. 5 method: 99th minus 30th percentile of 125 ms window levels).")
    w("- **Search:** Latin Hypercube (800 / 1500 / 2000 points for Basic / Group / Combined) then an elitist local search")
    w("  per target, on the real stems. Data: `demo_engine/analysis/sbr_matched_*.csv`.")
    w("")
    w("## 2. Which compressor the web test used, and how the values transfer to LL Dynamics")
    w("")
    w("The web test used **neither JUCE nor the browser's `DynamicsCompressorNode`**. It used the demo_engine's own C++ DSP")
    w("(`demo_engine/include/*.h`) compiled to WebAssembly; the sweeps ran the same C++ natively. LL Dynamics shares the")
    w("gain curve but not the detector:")
    w("")
    w("| | Web test (demo_engine) | LL Dynamics |")
    w("|---|---|---|")
    w("| Gain computer | soft knee, thesis Eq. 2 | identical |")
    w("| Detector input | mono (L+R)/2 | stereo-linked peak max(\\|L\\|,\\|R\\|) |")
    w("| Envelope | one-pole on the instantaneous **dB** level | one-pole on the **linear** peak, then dB |")
    w("| Look-ahead | none | none |")
    w("| Sidechain timing | sample-accurate | Priority -> Sidechain link, up to one block late |")
    w("| Max gain reduction | Basic ducking only | every mode |")
    w("")
    w("LL Dynamics therefore reads the same signal several dB hotter, by an amount that depends on the material and the")
    w("time constants, so **web thresholds must not be copied across**. The transfer used here:")
    w("")
    w("1. LL Dynamics was emulated offline (Compressor and Priority -> Sidechain paths). Checked against the real")
    w("   `LLDynamicsProcessor.cpp` on a real stem: max difference -168.6 dBFS, i.e. identical.")
    w("2. For each channel and scene, the LL Dynamics threshold that reproduces the web setting's **mean gain reduction**")
    w("   was solved (same ratio, knee, attack, release), then averaged over the three scenes.")
    w(f"3. One trim (dB) was applied so the LL Dynamics chain, with a {lag}-sample sidechain lag (one block at Unity's")
    w("   current 1024 DSP buffer), lands on the target SBR. The trim moves the Sidechain threshold (Basic, Combined) or")
    w("   the four background Compressor thresholds (Group compression).")
    w("")
    w("Section 4 gives the **LL Dynamics values to enter** (after step 3) and, for reference, the web values.")
    w("")
    w("## 3. Input levels at the compressor inputs (web test)")
    w("")
    w("Levels of each raw stem as it enters its compressor, in dBFS at file level (stereo RMS = mean of both channels'")
    w("power). LUFS is integrated loudness per ITU-R BS.1770-4. The Sidechain detector input is the Dialogue row.")
    w("**Playback/calibration level: none.** The web test had no SPL calibration; it played at whatever the listener's")
    w("system volume was. All levels and thresholds here are digital (dBFS), so Unity needs the offset (Delta) below.")
    w("")
    for scene in SCENES:
        w(f"**{SCENE_LABEL[scene]}**")
        w("")
        w("| Channel | RMS dBFS (whole clip) | RMS dBFS (speech-active) | Peak dBFS | LUFS (integrated) |")
        w("|---|---|---|---|---|")
        for r in levels:
            if r["scene"] == scene:
                w(f"| {r['channel']} | {f1(r['rms_dbfs'])} | {f1(r['rms_active_dbfs'])} | {f1(r['peak_dbfs'])} | {f1(r['lufs_integrated'])} |")
        w("")
    w("**Delta for Unity:** for each mixer group, Delta = (level at that group's LL Dynamics input in Unity) - (the")
    w("matching web level above), using the **same measure** for both (speech-active RMS dBFS is closest to what the")
    w("detectors see; LUFS is fine if that is what Unity's tools report). Add Delta to that group's LL Dynamics")
    w("threshold. For the Sidechain effects, use the **Dialogue group's** Delta (their detector listens to Dialogue).")
    w("")

    by_setting = defaultdict(list)
    for r in lld:
        by_setting[r["setting"]].append(r)

    w("## 4. Settings per mode")
    w("")
    for label, mode, values in settings:
        tgt = label.split("_")[-1]
        tname, tval, twin = TARGET[tgt]
        rows = by_setting.get(label, [])
        if not rows:
            continue
        trim = float(rows[0]["trim_db"])
        p = web_params(mode, values)
        w(f"### {MODE_LABEL[mode]}: {tgt} target, SBR {tval:+.1f} dB ({tname})")
        w("")
        w(f"Mixer snapshot: **{SNAPSHOT[mode]}**. Every makeup gain = 0 dB, Loudness Gate = 0 (off).")
        if mode in ("basic", "combined"):
            w("Dialogue group: LL Dynamics **Priority**, Priority Chan 1"
              + (", placed **before** its Compressor effect (the search keyed ducking on uncompressed Dialogue)." if mode == "combined" else "."))
            w("Music, Background Noise, Randomized FX (Safety/Other): LL Dynamics **Sidechain** (Mode 3, full band, not"
              " Sidechain Band), Priority Chan 1" + (", placed **after** each group's Compressor." if mode == "combined" else "."))
        if mode in ("comp", "combined"):
            w("Each group: LL Dynamics **Compressor** (Mode 1) with its own row below.")
        w("")
        w("**LL Dynamics values to enter** (web-test levels; add each group's Delta to its threshold, section 3):")
        w("")
        w("| Effect | Group | Threshold dB | Ratio | Knee dB | Attack ms | Release ms | Max GR dB | Makeup dB |")
        w("|---|---|---|---|---|---|---|---|---|")
        for r in rows:
            flag = " (below LL Dynamics' -60 dB slider limit before Delta)" if float(r["threshold_db"]) < -60 else ""
            w(f"| {r['stage']} | {r['channel']} | {f1(r['threshold_db'])}{flag} | {float(r['ratio']):.2f} | {f1(r['knee_db'])} | "
              f"{f1(r['attack_ms'])} | {float(r['release_ms']):.0f} | {f1(r['max_gr_db'])} | 0 |")
        w("")
        w(f"Includes a {trim:+.1f} dB SBR trim (section 2, step 3). Web-engine values these came from, for reference:")
        w("")
        w("| Stage | Group | Threshold dB | Ratio | Knee dB | Attack ms | Release ms | Max reduction dB |")
        w("|---|---|---|---|---|---|---|---|")
        if mode in ("comp", "combined"):
            for ch, key in zip(CHANNELS, ["dialogue", "music", "background", "safety", "other"]):
                dlg = key == "dialogue"
                w(f"| Compressor | {ch} | {f1(p[f'{key}_threshold_db'])} | {p[f'{key}_ratio']:.2f} | {f1(p['comp_knee_db'])} | "
                  f"{f1(p['dialogue_attack_ms' if dlg else 'background_attack_ms'])} | "
                  f"{p['dialogue_release_ms' if dlg else 'background_release_ms']:.0f} | none |")
        if mode in ("basic", "combined"):
            w(f"| Sidechain (Basic duck) | Music/Background/Safety/Other | {f1(p['duck_threshold_db'])} | {p['duck_ratio']:.2f} | "
              f"{f1(p['duck_knee_db'])} | {f1(p['duck_attack_ms'])} | {p['duck_release_ms']:.0f} | {f1(p['duck_max_reduction_db'])} |")
        w("")
        w("**Gain-reduction targets** (LL Dynamics with the values above, on the web-test stems; positive dB, as LL Dynamics")
        w("logs them per Meter ID). Mean = whole clip / speech-active; Max = largest instantaneous cut.")
        w("")
        w("| Effect | Group | " + " | ".join(f"{SCENE_LABEL[s]} mean | {SCENE_LABEL[s]} max" for s in SCENES) + " |")
        w("|---|---|" + "---|---|" * len(SCENES))
        for r in rows:
            cells = []
            for s in SCENES:
                cells.append(f"{f1(r[f'{s}_mean_gr_db'])} / {f1(r[f'{s}_mean_gr_active_db'])}")
                cells.append(f1(r[f"{s}_max_gr_db"]))
            w(f"| {r['stage']} | {r['channel']} | " + " | ".join(cells) + " |")
        w("")
        web_rows = [r for r in web_gr if r["setting"] == label]
        if web_rows:
            w("Web-engine gain reduction for the same setting (what the listening examples actually did):")
            w("")
            w("| Stage | Group | " + " | ".join(f"{SCENE_LABEL[s]} mean / max" for s in SCENES) + " |")
            w("|---|---|" + "---|" * len(SCENES))
            keys = []
            for r in web_rows:
                if (r["stage"], r["channel"]) not in keys:
                    keys.append((r["stage"], r["channel"]))
            for stage, ch in keys:
                cells = []
                for s in SCENES:
                    r = next(x for x in web_rows if x["scene"] == s and x["stage"] == stage and x["channel"] == ch)
                    cells.append(f"{f1(r['web_mean_gr_db'])} / {f1(r['web_max_gr_db'])}")
                w(f"| {stage} | {ch} | " + " | ".join(cells) + " |")
            w("")
        w("**SBR achieved** (dB; target " + f"{tval:+.1f}, J&H window {twin}):")
        w("")
        w(f"| Scene | Unprocessed | Web engine | LL Dynamics, trimmed, {lag}-sample lag | Dialogue dynamic range: raw -> processed (dB) |")
        w("|---|---|---|---|---|")
        for s in SCENES:
            sb = next(x for x in lld_sbr if x["setting"] == label and x["scene"] == s)
            un = next((x for x in renders if x["scene"] == s and x["label"] == "S0_unprocessed"), None)
            rr = next((x for x in renders if x["scene"] == s and x["label"] == label), None)
            dr = f"{f1(raw_range[s])} -> {f1(rr['dialogue_range_db'])}" if rr and s in raw_range else "n/a"
            w(f"| {SCENE_LABEL[s]} | {signed(un['sbr_db']) if un else 'n/a'} | {signed(sb['web_sbr_db'])} | "
              f"{signed(sb[f'lld_trimmed_sbr_db_lag{lag}'])} | {dr} |")
        w("")

    w("## 5. Calibrating in Unity")
    w("")
    w("1. **Build the chain** for the mode (section 4 effect order, Priority Chan 1, Loudness Gate off, makeup 0).")
    w("2. **Measure Delta per group** (section 3) during a representative conversation, at each LL Dynamics input.")
    w("   Add Delta to that group's thresholds; Dialogue's Delta goes on every Sidechain threshold.")
    w("3. **Check gain reduction** with Meter IDs (`*_dynamics.csv`, mean/max per conversation) against the targets in")
    w("   section 4 (speech-active mean is the closest match to a conversation window). Nudge thresholds to match.")
    w("4. **Final check is SBR at the ear** (the planned Hagerman & Olofsson tool, Docs/CLAUDE_HANDOFF.md). If gain")
    w("   reduction matches but SBR is off, trust SBR: move the same trim the search used (Sidechain threshold for")
    w("   Unmasked / Combined, background Compressor thresholds for GroupCompress) until it hits the target.")
    w("5. **Then** apply the planned equal-loudness correction (A) across modes; it is a static gain on the whole mix, so")
    w("   it does not change SBR.")
    w("")
    w("## 6. Caveats")
    w("")
    w("- **Different material.** These settings were found on the demo scenes (Construction, Public Transit,")
    w("  Restaurant stems), not on the coffee-shop sentences and effects. Delta corrects level, not dynamics, so the gain")
    w("  reduction targets are a guide and the measured SBR is the deciding check.")
    w("- **Basic unmasking cannot hit one SBR in every scene.** Its gain follows Dialogue only, so scenes that start at")
    w("  different SBRs end at different SBRs (see the spread in its SBR tables). Group compression and Combined compress")
    w("  each background group on its own level and land much closer across scenes.")
    w("- **Sidechain lag.** LL Dynamics' Priority -> Sidechain link can be one DSP block late (21 ms at 1024). The trim")
    w("  assumes that worst case; a 256 buffer would make the ducking react sooner.")
    w("- **Class mapping.** Unity has four groups for the five web classes: Safety and Other both correspond to")
    w("  Randomized FX (the effects participants detect, the J&H \"environmental sounds\"); Background Noise and Music map")
    w("  directly. If both Safety and Other rows differ, use Safety's for Randomized FX (it is the closer analog).")
    w("- **SBR is a level metric.** It is the J&H operating point, not a measured intelligibility score.")
    w("")
    w("## 7. Files")
    w("")
    w("- Listening examples, level-matched, same SBR per target: `demo_engine/paper-audio/sbr-matched/*.mp3` (also on the")
    w("  web page, section \"Same SBR, different processing\"); full-resolution WAVs in `demo_engine/exports/sbr_matched/`.")
    w("- Data: `demo_engine/analysis/sbr_matched_{basic,comp,combined}.csv` (every evaluated point),")
    w("  `sbr_matched_input_levels.tsv`, `sbr_matched_gain_reduction.tsv`, `sbr_matched_lld_settings.tsv`,")
    w("  `sbr_matched_lld_sbr.tsv`.")
    w("- Code: `demo_engine/analysis/sbr_matched_search.cpp` (search, renders, LL Dynamics emulation and report),")
    w("  `run_sbr_matched.sh` (whole pipeline).")
    w("")

    out = REPO / "unity" / "SBR_SETTINGS_HANDOFF.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")
    if UNITY_DOCS.is_dir():
        shutil.copy(out, UNITY_DOCS / "SBR_SETTINGS_HANDOFF.md")
        print(f"copied to {UNITY_DOCS / 'SBR_SETTINGS_HANDOFF.md'}")


if __name__ == "__main__":
    main()
