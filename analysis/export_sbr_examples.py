#!/usr/bin/env python3
"""Encodes the level-matched SBR renders to MP3 for the web page and writes
web/sbr-examples.js (window.SBR_EXAMPLES) from the renderer's stats file.

    python3 analysis/export_sbr_examples.py exports/sbr_matched
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "paper-audio" / "sbr-matched"
SCENES = [("construction", "Construction"), ("publictransit", "Public Transit"), ("restaurant", "Restaurant")]
LABELS = {
    "S0_unprocessed": "Unprocessed",
    "basic_HI": "Basic unmasking (HI target)", "comp_HI": "Group compression (HI target)",
    "combined_HI": "Combined (HI target)",
    "basic_NH": "Basic unmasking (NH target)", "comp_NH": "Group compression (NH target)",
    "combined_NH": "Combined (NH target)",
}


def main():
    render_dir = Path(sys.argv[1])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(render_dir / "render_stats.tsv") as f:
        stats = list(csv.DictReader(f, delimiter="\t"))
    scenes = []
    for key, label in SCENES:
        rows = []
        for order in LABELS:
            row = next((r for r in stats if r["scene"] == key and r["label"] == order), None)
            if not row:
                continue
            mp3 = OUT_DIR / f"{key}_{order}.mp3"
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(render_dir / f"{key}_{order}.wav"),
                            "-codec:a", "libmp3lame", "-b:a", "128k", str(mp3)], check=True)
            rows.append({"label": LABELS[order], "file": f"../paper-audio/sbr-matched/{mp3.name}",
                         "sbrDb": round(float(row["sbr_db"]), 2),
                         "dialogueRangeDb": round(float(row["dialogue_range_db"]), 2)})
        scenes.append({"scene": key, "label": label, "rows": rows})
    js = ("// Generated by analysis/export_sbr_examples.py - do not edit by hand.\n"
          "window.SBR_EXAMPLES = " + json.dumps({"scenes": scenes}, indent=2) + ";\n")
    (REPO / "web" / "sbr-examples.js").write_text(js)
    print(f"encoded {sum(len(s['rows']) for s in scenes)} MP3s -> {OUT_DIR}")


if __name__ == "__main__":
    main()
