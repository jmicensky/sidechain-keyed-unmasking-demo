#!/usr/bin/env python3
"""Turns sbr_matched_search's winning settings into the three places they're used.

Takes the settings chosen for the Unity test sequence (SELECTION below: a rank
in the "#1-#6 best distinct settings" tables of sbr_matched_settings_report.pdf,
ranked by the same code), rounds every value to the precision the web
sliders / Unity fields hold, and writes:

  analysis/sbr_matched_settings.tsv  - rounded settings, input to
                                       `sbr_matched_search --render` (so the
                                       renders use exactly the shipped values)
  web/sbr-presets.js                 - window.SBR_PRESETS for the web page
  analysis/sbr_matched_settings.md   - per-mode table mapped onto Unity's
                                       ProcessingSettings fields

Run after the searches, before rendering (analysis/run_sbr_matched.sh).
"""
import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ANALYSIS = REPO / "analysis"
MODES = ["basic", "comp", "combined"]
MODE_LABEL = {"basic": "Basic unmasking", "comp": "Group compression", "combined": "Combined"}
TARGET_LABEL = {"HI": "HI +5.1 dB", "NH": "NH +12.2 dB"}
CLASSES = ["dialogue", "music", "background", "safety", "other"]
CLASS_LABEL = ["Dialogue", "Music", "Background Noise", "Safety Alerts", "Other"]

# Settings chosen for the Unity test sequence: (mode, target) -> rank (#) in that
# mode/target's table in sbr_matched_settings_report.pdf. Chosen 2026-10-15.
# Combined is still provisional (#1) - not chosen yet.
SELECTION = {
    ("basic", "HI"): 1,
    ("basic", "NH"): 3,
    ("comp", "HI"): 1,
    ("comp", "NH"): 1,
    ("combined", "HI"): 1,
    ("combined", "NH"): 1,
}
PROVISIONAL = {("combined", "HI"), ("combined", "NH")}


def rounding(name):
    if name.endswith("_ratio"):
        return 2
    if name.endswith("release_ms"):
        return 0
    return 1


def dims_for(mode):
    with open(ANALYSIS / f"sbr_matched_{mode}.csv") as f:
        header = next(csv.reader(f))
    names = []
    for h in header[2:]:
        if h.startswith(("construction_", "publictransit_", "restaurant_")):
            break
        names.append(h)
    return names


def to_settings(mode, p):
    """Structured settings shared by the web presets and the Unity table."""
    s = {"mode": mode}
    if mode in ("basic", "combined"):
        s["duck"] = {
            "thresholdDb": p["duck_threshold_db"], "ratio": p["duck_ratio"], "kneeDb": p["duck_knee_db"],
            "attackMs": p["duck_attack_ms"], "releaseMs": p["duck_release_ms"],
            "maxReductionDb": p["duck_max_reduction_db"], "keyGainDb": 0.0,
        }
    if mode in ("comp", "combined"):
        groups = []
        for c in CLASSES:
            dlg = c == "dialogue"
            groups.append({
                "thresholdDb": p[f"{c}_threshold_db"], "ratio": p[f"{c}_ratio"], "kneeDb": p["comp_knee_db"],
                "attackMs": p["dialogue_attack_ms" if dlg else "background_attack_ms"],
                "releaseMs": p["dialogue_release_ms" if dlg else "background_release_ms"],
                "makeupGainDb": 0.0,
            })
        s["groups"] = groups
    return s


def main():
    tsv_lines, presets, md = [], [], []
    import sys
    sys.path.insert(0, str(ANALYSIS))
    from write_sbr_settings_tex import pick_distinct, read_csv, LABELS
    for mode in MODES:
        rows = read_csv(ANALYSIS / f"sbr_matched_{mode}.csv")
        names = dims_for(mode)
        for target in ("HI", "NH"):
            rank = SELECTION[(mode, target)]
            ranked, _ = pick_distinct(rows, [k for k in rows[0] if k in LABELS], target)
            chosen = ranked[rank - 1]
            vals = [round(float(chosen[n]), rounding(n)) for n in names]
            p = dict(zip(names, vals))
            tsv_lines.append(f"{mode}_{target}\t{mode}\t" + ",".join(repr(v) for v in vals))
            settings = to_settings(mode, p)
            note = " (provisional)" if (mode, target) in PROVISIONAL else ""
            presets.append({
                "id": f"{mode}_{target}",
                "label": f"{MODE_LABEL[mode]} - {TARGET_LABEL[target]} (#{rank}){note}",
                "target": target,
                "rank": rank,
                **settings,
            })
            md.append((mode, target, settings))

    (ANALYSIS / "sbr_matched_settings.tsv").write_text("\n".join(tsv_lines) + "\n")

    js = ("// Generated by analysis/export_sbr_presets.py - do not edit by hand.\n"
          "// SBR-matched settings (Johnson & Healy 2024 targets), one per mode x target.\n"
          "window.SBR_PRESETS = " + json.dumps(presets, indent=2) + ";\n")
    (REPO / "web" / "sbr-presets.js").write_text(js)

    out = ["# SBR-matched settings for the Unity test sequence", "",
           "Generated by `analysis/export_sbr_presets.py`. Every key gain and makeup gain is 0 dB.",
           "Field names are `ProcessingSettings` / `GroupCompressorSettings` (unity/Runtime/).", ""]
    for mode, target, s in md:
        out.append(f"## {MODE_LABEL[mode]} - {TARGET_LABEL[target]}  (`PS_{mode}_{target}`)")
        out.append("")
        flags = [f"unmaskEnabled = {'true' if 'duck' in s else 'false'}",
                 f"enhancementEnabled = {'true' if 'groups' in s else 'false'}"]
        if "duck" in s:
            flags += ["keyClass = Dialogue", "duckMode = Basic"]
        if "groups" in s:
            flags += ["enhancementBandMode = SingleBand"]
        if mode == "combined":
            flags += ["keyDetectorTap = PreEnhancement"]
        out.append("`" + "`, `".join(flags) + "`")
        out.append("")
        if "duck" in s:
            d = s["duck"]
            out += ["| thresholdDb | ratio | kneeDb | attackMs | releaseMs | maxReductionDb | keyGainDb |",
                    "|---|---|---|---|---|---|---|",
                    f"| {d['thresholdDb']} | {d['ratio']} | {d['kneeDb']} | {d['attackMs']} | {d['releaseMs']:.0f} | "
                    f"{d['maxReductionDb']} | 0 |", ""]
        if "groups" in s:
            out += ["| enhancement[] | thresholdDb | ratio | kneeDb | attackMs | releaseMs | makeupGainDb |",
                    "|---|---|---|---|---|---|---|"]
            for label, g in zip(CLASS_LABEL, s["groups"]):
                out.append(f"| {label} | {g['thresholdDb']} | {g['ratio']} | {g['kneeDb']} | {g['attackMs']} | "
                           f"{g['releaseMs']:.0f} | 0 |")
            out.append("")
    (ANALYSIS / "sbr_matched_settings.md").write_text("\n".join(out))
    print(f"wrote {len(presets)} presets")


if __name__ == "__main__":
    main()
