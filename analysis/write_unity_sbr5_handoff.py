#!/usr/bin/env python3
"""Writes the Unity handoff for the three +5.0 dB SBR settings (one per mixer
snapshot), from the analysis/sbr5_* outputs (see analysis/run_sbr5.sh).

Output: unity/SBR5_UNITY_SETTINGS.md, copied to the Unity project's Docs/.
"""
import csv
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
A = REPO / "analysis"
UNITY_DOCS = Path.home() / "Documents/UIC/THESIS RESEARCH/Modified_Johnson_Healy/Docs"
TARGET = 5.0
TOL = 0.10
MODES = [("basic", "Unmasked", "Basic unmasking"),
         ("comp", "GroupCompress", "Group compression"),
         ("combined", "GroupCompressed>Unmasked", "Combined (group compression, then unmasking)")]
SCENE_LABEL = {"construction": "Construction", "publictransit": "Public Transit", "restaurant": "Restaurant"}
GROUPS = [("dialogue", "Dialogue"), ("music", "Music"), ("background", "Background Noise"),
          ("safety", "Safety (Randomized FX)"), ("other", "Other (Randomized FX)")]


def tsv(path):
    with open(path) as f:
        return list(csv.DictReader(f, delimiter="\t"))


def dims_for(mode):
    with open(A / f"sbr5_{mode}.csv") as f:
        header = next(csv.reader(f))
    names = []
    for h in header[2:]:
        if h.startswith(("construction_", "publictransit_", "restaurant_")):
            break
        names.append(h)
    return names


def f1(x):
    return f"{float(x):.1f}"


def main():
    settings = {l.split("\t")[1]: l.split("\t")[2] for l in (A / "sbr5_settings.tsv").read_text().splitlines() if l}
    evals = tsv(A / "sbr5_eval.tsv")
    levels = tsv(A / "sbr5_input_levels.tsv")
    lld = tsv(A / "sbr5_lld_settings.tsv")
    lld_sbr = tsv(A / "sbr5_lld_sbr.tsv")
    web_gr = tsv(A / "sbr5_gain_reduction.tsv")
    renders = tsv(REPO / "exports/sbr5_construction/render_stats.tsv")
    lag = next(k for k in lld_sbr[0] if k.startswith("lld_trimmed_sbr_db_lag")).split("lag")[-1]

    o = []
    w = o.append
    w("# Unity settings: one dynamics setting per mixer snapshot, all at SBR +5.0 dB")
    w("")
    w("Generated by `demo_engine/analysis/write_unity_sbr5_handoff.py` (pipeline: `demo_engine/analysis/run_sbr5.sh`).")
    w("Supersedes the HI/NH choices in `SBR_SETTINGS_HANDOFF.md` for the test sequence; that document still explains the")
    w("metric, the LL Dynamics transfer and the calibration method in more depth.")
    w("")
    w("## Decision (2026-10-15)")
    w("")
    w(f"- **One SBR for every condition: +{TARGET:.1f} dB, tolerance +-{TOL:.2f} dB** (Johnson & Healy 2024 SBR: speech-active")
    w("  RMS of processed Dialogue / RMS of the processed sum of Music, Background, Safety and Other; broadband, unweighted).")
    w("- **Reference scene: Construction** (judged the most realistic-sounding demo scene). The settings were searched so")
    w("  that Construction lands on target; the other two demo scenes are listed for reference only.")
    w("- **Dynamics only:** key gain and every makeup gain are 0 dB. In Group compression and Combined, Dialogue is itself")
    w("  compressed (ratio 2-4:1, 1.5-6 dB mean gain reduction) for intelligibility.")
    w("- Among settings within +-0.05 dB of the target, the search kept the one with the least gain reduction.")
    w("")
    w("| Mixer snapshot | Condition | SBR on Construction (web engine) | SBR with LL Dynamics values below |")
    w("|---|---|---|---|")
    for mode, snap, label in MODES:
        web = next(e for e in evals if e["id"] == f"{mode}_T" and e["scene"] == "construction")
        ls = next(x for x in lld_sbr if x["setting"] == f"{mode}_T")
        w(f"| **{snap}** | {label} | {float(web['sbr_db']):+.2f} dB | {float(ls[f'lld_trimmed_sbr_db_lag{lag}']):+.2f} dB |")
    un = next(r for r in renders if r["label"] == "S0_unprocessed")
    w(f"| Unprocessed | none | {float(un['sbr_db']):+.2f} dB | - |")
    w("")
    w(f"LL Dynamics column: offline emulation of the plugin (verified identical to `LLDynamicsProcessor.cpp`) with a")
    w(f"{lag}-sample (one block) Priority -> Sidechain lag, on the Construction stems at web-test levels.")
    w("")

    w("## Effect chains")
    w("")
    w("All LL Dynamics effects: Makeup 0 dB, Loudness Gate 0 (off), Priority Chan 1. Give each a Meter ID for logging.")
    w("")
    w("- **Unmasked:** Dialogue = Priority (Mode 2). Music, Background Noise, Randomized FX = Sidechain (Mode 3, full band).")
    w("- **GroupCompress:** every group (Dialogue, Music, Background Noise, Randomized FX) = Compressor (Mode 1).")
    w("- **GroupCompressed>Unmasked:** Dialogue = Priority **then** Compressor (Priority first, so ducking is keyed on")
    w("  uncompressed Dialogue, as searched). Music, Background Noise, Randomized FX = Compressor **then** Sidechain.")
    w("- Randomized FX holds what the web test split into Safety and Other: use the **Safety** row for it.")
    w("")

    w("## LL Dynamics values to enter")
    w("")
    w("Thresholds are for the web-test input levels (next section). In Unity, add each group's Delta to its thresholds")
    w("(Dialogue's Delta for the Sidechain threshold), then confirm SBR = +5.0 +-0.1 dB at the ear.")
    w("")
    for mode, snap, label in MODES:
        rows = [r for r in lld if r["setting"] == f"{mode}_T"]
        trim = float(rows[0]["trim_db"])
        w(f"### {snap} - {label}")
        w("")
        w("| Effect | Group | Threshold dB | Ratio | Knee dB | Attack ms | Release ms | Max GR dB | Makeup dB |")
        w("|---|---|---|---|---|---|---|---|---|")
        for r in rows:
            group = r["channel"]
            if group == "Music/Background/Safety/Other":
                group = "Music, Background Noise, Randomized FX"
            w(f"| {r['stage']} | {group} | {f1(r['threshold_db'])} | {float(r['ratio']):.2f} | {f1(r['knee_db'])} | "
              f"{f1(r['attack_ms'])} | {float(r['release_ms']):.0f} | {f1(r['max_gr_db'])} | 0 |")
        w("")
        w(f"Includes a {trim:+.1f} dB trim so the LL Dynamics chain lands on +5.0 dB (moved the "
          + ("Sidechain threshold" if mode != "comp" else "four background Compressor thresholds") + ").")
        w("")
        w("Gain-reduction targets on Construction (LL Dynamics, positive dB as logged per Meter ID):")
        w("")
        w("| Effect | Group | Mean, whole clip | Mean, speech-active | Max |")
        w("|---|---|---|---|---|")
        for r in rows:
            w(f"| {r['stage']} | {r['channel']} | {f1(r['construction_mean_gr_db'])} | "
              f"{f1(r['construction_mean_gr_active_db'])} | {f1(r['construction_max_gr_db'])} |")
        w("")
        p = dict(zip(dims_for(mode), (float(v) for v in settings[mode].split(","))))
        w("<details><summary>Web-engine values (for reference; do not enter these in LL Dynamics)</summary>")
        w("")
        w("| Stage | Group | Threshold dB | Ratio | Knee dB | Attack ms | Release ms | Max reduction dB |")
        w("|---|---|---|---|---|---|---|---|")
        if mode in ("comp", "combined"):
            for key, name in GROUPS:
                dlg = key == "dialogue"
                w(f"| Compressor | {name} | {f1(p[f'{key}_threshold_db'])} | {p[f'{key}_ratio']:.2f} | {f1(p['comp_knee_db'])} | "
                  f"{f1(p['dialogue_attack_ms' if dlg else 'background_attack_ms'])} | "
                  f"{p['dialogue_release_ms' if dlg else 'background_release_ms']:.0f} | none |")
        if mode in ("basic", "combined"):
            w(f"| Sidechain | Music, Background Noise, Randomized FX | {f1(p['duck_threshold_db'])} | {p['duck_ratio']:.2f} | "
              f"{f1(p['duck_knee_db'])} | {f1(p['duck_attack_ms'])} | {p['duck_release_ms']:.0f} | "
              f"{f1(p['duck_max_reduction_db'])} |")
        w("")
        web_rows = [r for r in web_gr if r["setting"] == f"{mode}_T"]
        w("Web-engine gain reduction on Construction (mean / max): " + "; ".join(
            f"{r['stage']} {r['channel']} {f1(r['web_mean_gr_db'])} / {f1(r['web_max_gr_db'])} dB" for r in web_rows) + ".")
        w("")
        w("</details>")
        w("")

    w("## Input levels at the compressor inputs (Construction, web test)")
    w("")
    w("Digital levels of each raw stem (dBFS, stereo RMS; LUFS per ITU-R BS.1770-4). No SPL calibration was used in the")
    w("web test. **Delta** per Unity group = (its level at the LL Dynamics input in Unity) - (this level), same measure on")
    w("both sides; speech-active RMS is closest to what the detectors see.")
    w("")
    w("| Channel | RMS (whole clip) | RMS (speech-active) | Peak | LUFS |")
    w("|---|---|---|---|---|")
    for r in levels:
        if r["scene"] == "construction":
            w(f"| {r['channel']} | {f1(r['rms_dbfs'])} | {f1(r['rms_active_dbfs'])} | {f1(r['peak_dbfs'])} | {f1(r['lufs_integrated'])} |")
    w("")

    w("## Reference: the same settings on the other demo scenes (web engine)")
    w("")
    w("Not part of the target; shows how much each mode's SBR depends on the material. Basic unmasking follows")
    w("Dialogue's level only, so it moves most between scenes.")
    w("")
    w("| Snapshot | " + " | ".join(SCENE_LABEL[s] for s in SCENE_LABEL) + " |")
    w("|---|---|---|---|")
    for mode, snap, _ in MODES:
        cells = []
        for s in SCENE_LABEL:
            e = next(x for x in evals if x["id"] == f"{mode}_T" and x["scene"] == s)
            cells.append(f"{float(e['sbr_db']):+.2f}")
        w(f"| {snap} | " + " | ".join(cells) + " |")
    w("")
    w("Dialogue dynamic range on Construction (99th - 30th percentile of 125 ms levels, J&H Fig. 5 method): "
      + ", ".join(f"{r['label'].replace('S0_unprocessed', 'unprocessed').replace('_T', '')} {f1(r['dialogue_range_db'])} dB"
                  for r in renders) + ".")
    w("")

    w("## Getting exactly +5.0 +-0.1 dB in Unity")
    w("")
    w("1. Enter the values above (plus each group's Delta) in the snapshot's LL Dynamics effects.")
    w("2. Measure SBR at the ear for that snapshot on the test material (the planned Hagerman & Olofsson tool).")
    w("3. If it is off, move only the trimmed thresholds (Sidechain threshold for Unmasked and GroupCompressed>Unmasked;")
    w("   the background-group Compressor thresholds together for GroupCompress) until it reads +5.0 +-0.1 dB.")
    w("4. Check the logged gain reduction against the targets above, so the processing character still matches.")
    w("5. Apply the equal-loudness correction afterwards; a whole-mix gain does not change SBR.")
    w("")
    w("Why step 3 is needed: the coffee-shop material is not the Construction stems, and LL Dynamics' detector differs")
    w("from the web engine's, so the transferred values start close but are not guaranteed to land within 0.1 dB.")
    w("")
    w("Listening examples (Construction, level-matched): `demo_engine/paper-audio/sbr5-construction/*.mp3`.")
    w("")

    out = REPO / "unity" / "SBR5_UNITY_SETTINGS.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")
    if UNITY_DOCS.is_dir():
        shutil.copy(out, UNITY_DOCS / out.name)
        print(f"copied to {UNITY_DOCS / out.name}")


if __name__ == "__main__":
    main()
